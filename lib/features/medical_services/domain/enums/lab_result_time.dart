/// Expected turnaround timeframe for laboratory test results.
enum LabResultTime {
  /// Results are ready on the same day.
  sameDay,

  /// Results are ready in one business day.
  oneDay,

  /// Results are ready in two days.
  twoDays,

  /// Results are ready in three days.
  threeDays,

  /// Results are ready in one week.
  oneWeek,
}
